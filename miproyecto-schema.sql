--  DDL for Trigger TRG_CONTROL_ANIO_MATRICULA
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE TRIGGER "PROYECTO"."TRG_CONTROL_ANIO_MATRICULA" 
BEFORE INSERT ON ALUMNO_TIENE_ASIGNATURA
FOR EACH ROW
DECLARE
    v_anio_actual NUMBER(4);
BEGIN
    -- Extraemos el año actual del sistema
    v_anio_actual := TO_NUMBER(TO_CHAR(SYSDATE, 'YYYY'));

    -- Si intentan matricular en un año distinto, saltará el error
    IF :NEW.ANO <> v_anio_actual THEN
        RAISE_APPLICATION_ERROR(-20005, 'Error: No se permiten matrículas fuera del año académico en curso (' || v_anio_actual || ').');
    END IF;
END;

/
ALTER TRIGGER "PROYECTO"."TRG_CONTROL_ANIO_MATRICULA" ENABLE;
