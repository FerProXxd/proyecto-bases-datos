--  DDL for Function PROFESOR_DE_ALUMNO
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "PROYECTO"."PROFESOR_DE_ALUMNO" 
(
  DNI_ALUMNO IN ALUMNO.DNI%TYPE 
) RETURN PROFESOR.NOMBREPRO%TYPE AS
RESPUESTA PROFESOR.NOMBREPRO%TYPE;
BEGIN
    SELECT PR.NOMBREPRO
    INTO RESPUESTA
    FROM PROFESOR PR
    JOIN ASIGNATURA ASI ON PR.CODIGOPROFESOR = ASI.CODIGOPROFESOR
    JOIN alumno_tiene_asignatura ALT ON asi.codigoasignatura = alt.codigoasignatura
    JOIN ALUMNO AL ON alt.dni = al.dni
    WHERE al.dni = DNI_ALUMNO;
    RETURN RESPUESTA;
END;

