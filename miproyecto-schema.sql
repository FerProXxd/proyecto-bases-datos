--  DDL for Trigger TRG_VERIFICAR_JEFE_DEP
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE TRIGGER "PROYECTO"."TRG_VERIFICAR_JEFE_DEP" 
BEFORE INSERT OR UPDATE ON DEPARTAMENTO
FOR EACH ROW
DECLARE
    v_dep_profesor VARCHAR2(50);
BEGIN
    IF :NEW.JEFE IS NOT NULL THEN
        SELECT NOMBREDEP INTO v_dep_profesor
        FROM PROFESOR
        WHERE CODIGOPROFESOR = :NEW.JEFE;

        IF v_dep_profesor <> :NEW.NOMBREDEP THEN
            RAISE_APPLICATION_ERROR(-20003, 'Error: El profesor asignado como jefe pertenece al departamento de ' || v_dep_profesor || ', no a ' || :NEW.NOMBREDEP);
        END IF;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20004, 'Error: El código de profesor introducido no existe.');
END;

/
ALTER TRIGGER "PROYECTO"."TRG_VERIFICAR_JEFE_DEP" ENABLE;
